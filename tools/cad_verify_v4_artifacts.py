"""Independent same-card artifact checks; no constructor plan or proxy requirement.

Only explicitly hash-bound Python feature dependencies may be restored. This is
an offline development checker, not an OS sandbox for untrusted extension code.
Submitted FCStd/STEP bytes are never saved, repaired or regenerated by checking.
"""
import base64
import importlib
import importlib.util
import json
import math
from pathlib import Path, PurePosixPath
import sys
import time
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / 'design/cad-harness-verify-v4/schemas/artifact-bundle.schema.json'
SCALAR_TYPES = {'App::PropertyFloat', 'App::PropertyFloatConstraint', 'App::PropertyLength',
                'App::PropertyDistance', 'App::PropertyAngle', 'App::PropertyInteger',
                'App::PropertyIntegerConstraint'}
RESERVED_MODULES = {'FreeCAD', 'Part', 'Sketcher', 'math', 'sys', 'os', 'builtins',
                    'importlib', 'json', 'tools'}


def _module(name):
    return importlib.import_module(('tools.' if __package__ else '') + name)


def _file(record, parent):
    s1, ledger = _module('cad_verify_v4_s1'), _module('cad_verify_v4_ledger')
    raw = Path(record['path'])
    path = s1.safe_path(raw if raw.is_absolute() else parent / raw, regular=True)
    if path.stat().st_size != record['bytes'] or ledger.file_sha(path) != record['sha256']:
        raise ValueError('artifact_dependency_changed:' + str(path))
    return path


def load_bundle(path, *, profile=None):
    """Admit explicit artifact/dependency bytes before any document is opened."""
    s1, ledger, plans = (_module(n) for n in ('cad_verify_v4_s1', 'cad_verify_v4_ledger', 'cad_verify_v4_plans'))
    path = s1.safe_path(path, regular=True)
    value, schema = ledger.read_json(path), ledger.read_json(SCHEMA)
    plans._check(value, schema, schema, 'artifact_bundle')
    if profile is not None and value['profile'] != profile:
        raise ValueError('artifact_bundle_profile_mismatch')
    files = {key: _file(value[key], path.parent) for key in ('native', 'step')}
    if files['native'].suffix.casefold() != '.fcstd' or files['step'].suffix.casefold() not in ('.step', '.stp'):
        raise ValueError('artifact_native_step_file_types')
    if files['native'] == files['step']:
        raise ValueError('artifact_representations_not_distinct')
    extensions = {}
    for record in value['extensions']:
        name = record['module']
        if name in extensions or name.split('.')[0] in RESERVED_MODULES - {'tools'} or name == 'tools':
            raise ValueError('artifact_extension_module_collision')
        source = _file(record, path.parent)
        if source.suffix != '.py' or source.stem != name.split('.')[-1]:
            raise ValueError('artifact_extension_module_source_mismatch')
        if name.startswith('tools.') and source != ROOT / 'tools' / (name.removeprefix('tools.').replace('.', '/') + '.py'):
            raise ValueError('artifact_extension_cannot_replace_tools_module')
        extensions[name] = source
    for probe in value['probes']:
        if probe['kind'] in ('scalar', 'sketch_constraint') and probe['delta'] == 0:
            raise ValueError('artifact_probe_zero_delta')
        if probe['kind'] in ('vector', 'vector_list') and not any(probe['delta_mm']):
            raise ValueError('artifact_probe_zero_delta')
    return value, files, extensions


def _python_value(node):
    value = node.get('value', '')
    if node.get('encoded') == 'yes':
        value = base64.b64decode(value, validate=True).decode('utf-8')
    if value in ('', 'None'):
        return None
    # JSON-only persistence rejects pickle and arbitrary serialized evaluation.
    return json.loads(value, parse_constant=lambda _: (_ for _ in ()).throw(ValueError('native_nonfinite_state')))


def _archive_root(native):
    """Read only the bounded data-only document header from actual saved bytes."""
    with zipfile.ZipFile(native) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)) or 'Document.xml' not in names:
            raise ValueError('native_archive_members')
        for name in names:
            normalized = name.replace('\\', '/')
            member = PurePosixPath(normalized)
            if member.is_absolute() or '..' in member.parts or ':' in normalized:
                raise ValueError('native_archive_member_path')
        info = archive.getinfo('Document.xml')
        # Engineering input bound, not a geometry/manufacturing tolerance.
        if info.file_size > 64 * 1024 * 1024:
            raise ValueError('native_document_xml_resource_limit')
        root = ET.fromstring(archive.read(info))
    return root


def _serialized_modules(root):
    required = set()
    for node in root.iter('Python'):
        _python_value(node)
        module, cls = node.get('module'), node.get('class')
        if module or cls:
            if not module or not cls or not cls.isidentifier() or cls.startswith('__'):
                raise ValueError('native_undeclared_python_dependency')
            required.add(module)
    return required


def restoration_modules(native):
    """Exact serialized restoration dependencies; ordinary native files yield []."""
    return sorted(_serialized_modules(_archive_root(native)))


def _guard_archive(native, extensions, allowed_files):
    """Reject undeclared Python restoration and external document/file reads."""
    s1 = _module('cad_verify_v4_s1')
    root = _archive_root(native)
    required = _serialized_modules(root)
    if required - set(extensions):
        raise ValueError('native_undeclared_python_dependency')
    if required != set(extensions):
        raise ValueError('native_unused_python_dependency')
    for node in root.iter('Property'):
        kind = node.get('type', '')
        if 'XLink' in kind:
            # Native handover is self-contained; no linked external documents.
            raise ValueError('native_external_document_link')
        if kind in ('App::PropertyFile', 'App::PropertyPath', 'App::PropertyFileIncluded'):
            for item in node:
                value = item.get('value', '')
                if not value:
                    continue
                raw = Path(value)
                resolved = s1.safe_path(raw if raw.is_absolute() else native.parent / raw, regular=True)
                if resolved not in allowed_files:
                    raise ValueError('native_unbound_file_dependency')
    return required


def _import_extensions(extensions):
    for name, path in extensions.items():
        old = sys.modules.get(name)
        if old is not None:
            source = getattr(old, '__file__', None)
            if source is None or Path(source).absolute() != path:
                raise ValueError('native_loaded_extension_identity_mismatch')
            continue
        if name.startswith('tools.'):
            if str(ROOT) not in sys.path:
                sys.path.insert(0, str(ROOT))
            module = importlib.import_module(name)
            if Path(module.__file__).absolute() != path:
                raise ValueError('native_extension_import_path_mismatch')
        else:
            if '.' in name:
                raise ValueError('native_external_extension_must_be_single_module')
            spec = importlib.util.spec_from_file_location(name, path)
            if spec is None or spec.loader is None:
                raise ValueError('native_extension_load_failed')
            module = importlib.util.module_from_spec(spec)
            sys.modules[name] = module
            try:
                spec.loader.exec_module(module)
            except BaseException:
                sys.modules.pop(name, None)
                raise


def _body(doc, name, *, expected_solids=1):
    if expected_solids > 1:
        output = doc.getObject(name) if name is not None else None
        if output is None or output.TypeId not in ('Part::Feature', 'Part::FeaturePython', 'Part::Compound'):
            raise ValueError('native_named_compound_output_required')
        return output
    bodies = [obj for obj in doc.Objects if obj.TypeId == 'PartDesign::Body']
    if len(bodies) != 1 or (name is not None and bodies[0].Name != name):
        raise ValueError('native_single_output_body_required')
    return bodies[0]


def _shape_difference(a, b):
    """Exact volume difference; bounds/volume equality never proves restoration."""
    if a.isSame(b) and a.Orientation == b.Orientation:
        return 0.
    def solid_tree(shape):
        if shape.ShapeType == 'Solid':
            return True
        return (shape.ShapeType in ('Compound', 'CompSolid') and
                all(solid_tree(child) for child in shape.childShapes()))
    if not solid_tree(a) or not solid_tree(b):
        # Decomposing only Solids must never discard an unrelated shell/face.
        return float(a.cut(b).Volume + b.cut(a).Volume)
    left, right = a.BoundBox, b.BoundBox
    if (left.XMax < right.XMin or right.XMax < left.XMin
            or left.YMax < right.YMin or right.YMax < left.YMin
            or left.ZMax < right.ZMin or right.ZMax < left.ZMin):
        # Strictly separated enclosing boxes prove that intersection is empty.
        return float(a.Volume + b.Volume)
    # Geometry-preserving copies normalize redundant native Location chains;
    # otherwise a snapshot and an unchanged live solid serialize differently.
    # Equality still includes geometry, topology, orientation and placement.
    if a.copy().exportBrepToString() == b.copy().exportBrepToString():
        return 0.
    left_solids, right_solids = list(a.Solids), list(b.Solids)
    if len(left_solids) > 1 or len(right_solids) > 1:
        common_left, common_right = set(), set()
        for i, solid in enumerate(left_solids):
            match = next((j for j, other in enumerate(right_solids)
                          if j not in common_right and solid.isSame(other)
                          and solid.Orientation == other.Orientation), None)
            if match is not None:
                common_left.add(i)
                common_right.add(match)
        by_brep = {}
        for j, solid in enumerate(right_solids):
            if j not in common_right:
                by_brep.setdefault(solid.copy().exportBrepToString(), []).append(j)
        for i, solid in enumerate(left_solids):
            if i not in common_left:
                matches = by_brep.get(solid.copy().exportBrepToString())
                if matches:
                    common_left.add(i)
                    common_right.add(matches.pop())
        if common_left:
            import Part

            def remaining_difference(solids, common, opposing):
                remaining = [solid for i, solid in enumerate(solids) if i not in common]
                if not remaining:
                    return 0.
                source = remaining[0] if len(remaining) == 1 else Part.makeCompound(remaining)
                # A=C∪X, B=C∪Y implies A\B=X\B, NOT X\Y: retained
                # common material can still cover unmatched, overlapping solids.
                return source.cut(opposing).Volume

            return float(remaining_difference(left_solids, common_left, b)
                         + remaining_difference(right_solids, common_right, a))
    return float(a.cut(b).Volume + b.cut(a).Volume)


def _probes(doc, supplied):
    if supplied:
        return supplied
    # Ordinary native Pad/Pocket files need no bespoke handover annotations.
    return [dict(kind='scalar', object=obj.Name, property='Length',
                 delta=max(abs(float(obj.Length)) * .01, .001))
            for obj in doc.Objects if obj.TypeId in ('PartDesign::Pad', 'PartDesign::Pocket')]


def _edit_probe(App, doc, probe):
    obj = doc.getObject(probe['object'])
    if obj is None:
        raise ValueError('native_probe_object_missing')
    kind = probe['kind']
    if kind == 'sketch_constraint':
        if obj.TypeId != 'Sketcher::SketchObject' or not 0 <= probe['constraint'] < obj.ConstraintCount:
            raise ValueError('native_probe_sketch_constraint')
        old = obj.getDatum(probe['constraint'])
        value = float(old.Value) + probe['delta']
        unit = str(old.Unit)
        obj.setDatum(probe['constraint'], App.Units.Quantity(value, old.Unit))
        return lambda: obj.setDatum(probe['constraint'], old), {'old': old.Value, 'new': value, 'unit': unit}
    name = probe['property']
    if name not in obj.PropertiesList or 'ReadOnly' in obj.getEditorMode(name):
        raise ValueError('native_probe_property_not_editable')
    if 'NoRecompute' in obj.getPropertyStatus(name):
        raise ValueError('native_probe_property_no_recompute')
    type_id, old = obj.getTypeIdOfProperty(name), getattr(obj, name)
    if kind == 'scalar':
        if type_id not in SCALAR_TYPES:
            raise ValueError('native_probe_scalar_property_type')
        value = float(old) + probe['delta']
        if type_id in ('App::PropertyInteger', 'App::PropertyIntegerConstraint'):
            if int(value) != value:
                raise ValueError('native_probe_integer_delta')
            value = int(value)
        detail = {'old': float(old), 'new': value}
    elif kind == 'vector':
        if type_id != 'App::PropertyVector':
            raise ValueError('native_probe_vector_property_type')
        old = App.Vector(old)
        value = old + App.Vector(*probe['delta_mm'])
        detail = {'old': list(old), 'new': list(value)}
    elif kind == 'vector_list':
        if type_id != 'App::PropertyVectorList' or not 0 <= probe['index'] < len(old):
            raise ValueError('native_probe_vector_list_property_type')
        old = [App.Vector(v) for v in old]
        value = [App.Vector(v) for v in old]
        value[probe['index']] += App.Vector(*probe['delta_mm'])
        detail = {'old': list(old[probe['index']]), 'new': list(value[probe['index']])}
    else:
        if kind != 'text' or type_id != 'App::PropertyString':
            raise ValueError('native_probe_text_property_type')
        value = old + probe['suffix']
        detail = {'old': old, 'new': value}
    setattr(obj, name, value)
    return lambda: setattr(obj, name, old), detail


def check_document(doc, body, *, expected_solids=1):
    """Native structure/state only: no harness-specific status-token fields."""
    compiler = _module('cad_verify_v4_compile')
    if body.Document != doc or doc.getObject(body.Name) != body:
        raise ValueError('native_output_document')
    if expected_solids == 1:
        if body.TypeId != 'PartDesign::Body' or body.Tip is None:
            raise ValueError('native_body_tip')
        if [obj for obj in doc.Objects if obj.TypeId == 'PartDesign::Body'] != [body]:
            raise ValueError('native_body_count')
        compiler.shape_measurements(body.Tip.Shape)
    elif body.TypeId not in ('Part::Feature', 'Part::FeaturePython', 'Part::Compound'):
        raise ValueError('native_compound_output_type')
    for obj in doc.Objects:
        if any(state in ('Invalid', 'Error', 'Touched') for state in obj.State):
            raise ValueError('native_document_state:' + obj.Name)
    compiler.shape_measurements(body.Shape, expected_solids=expected_solids)


def operative(App, doc, body, supplied, *, expected_solids=1):
    """Prove output consumption/restoration, covering every source solid."""
    check_document(doc, body, expected_solids=expected_solids)
    records = []
    specs = _probes(doc, supplied)
    for probe in specs:
        before = body.Shape.copy()
        numerical_floor = max(1e-10, before.Volume * 1e-12)
        changed_solids = []
        restore, row = None, dict(probe=probe, operative=False, restored=False,
                                  numerical_floor_mm3=numerical_floor)
        try:
            restore, values = _edit_probe(App, doc, probe)
            row.update(values)
            doc.recompute()
            after = body.Shape
            invalidated = after.isNull()
            row['invalidated_on_rejected_edit'] = invalidated
            if invalidated:
                row['operative'] = True
                changed_solids = list(range(expected_solids))
            else:
                _module('cad_verify_v4_compile').shape_measurements(
                    after, expected_solids=expected_solids)
                difference = _shape_difference(before, after)
                row.update(symmetric_difference_mm3=difference,
                           operative=math.isfinite(difference) and difference > numerical_floor)
                # Each submitted piece must participate in an actual output edit;
                # an operative Pad on one body cannot certify unrelated cached pieces.
                if expected_solids == 1:
                    # The whole-output difference already measures its only solid.
                    changed_solids = [0] if row['operative'] else []
                else:
                    names = ('XMin', 'XMax', 'YMin', 'YMax', 'ZMin', 'ZMax')
                    candidates = []
                    for other in after.Solids:
                        bounds = other.BoundBox
                        candidates.append((other, tuple(getattr(bounds, name) for name in names)))
                    for index, solid in enumerate(before.Solids):
                        bounds = solid.BoundBox
                        coordinates = tuple(getattr(bounds, name) for name in names)
                        ordered = sorted(candidates, key=lambda item:
                                         sum(abs(x-y) for x, y in zip(coordinates, item[1])))
                        floor = max(1e-10, solid.Volume * 1e-12)
                        # Bounds only order likely matches; an actual symmetric
                        # difference at/below the floor still proves each match.
                        if all(_shape_difference(solid, other) > floor for other, _ in ordered):
                            changed_solids.append(index)
        except Exception as exc:
            row.update(error_type=type(exc).__name__, error=str(exc))
        finally:
            if restore is not None:
                restore()
                doc.recompute()
                check_document(doc, body, expected_solids=expected_solids)
                difference = _shape_difference(before, body.Shape)
                row.update(restore_difference_mm3=difference,
                           restored=math.isfinite(difference) and difference <= numerical_floor)
                if not row['restored']:
                    raise ValueError('native_probe_did_not_restore_geometry')
        records.append(row)
        row['changed_solid_indices'] = changed_solids
    covered = {index for row in records if row['operative'] and row['restored']
               for index in row['changed_solid_indices']}
    editable = (bool(records) and all(row['operative'] and row['restored'] for row in records)
                and covered == set(range(expected_solids)))
    return {'status': 'PASS' if editable else 'FAIL' if records else 'UNVERIFIED', 'probes': records}, editable


def execution_manifest_record(execution):
    """Produce a worker-bound authority record only for an actual typed scope."""
    trials = _module('cad_verify_v4_trials')
    if isinstance(execution, trials.PlanExecution):
        session = execution.session
    elif isinstance(execution, trials.TrialSession):
        session = execution
    else:
        raise ValueError('neutral_checker_authorized_execution_scope_required')
    if not isinstance(session, trials.TrialSession):
        raise ValueError('neutral_checker_authorized_session_required')
    path = _module('cad_verify_v4_s1').safe_path(session.manifest_path, regular=True)
    return dict(path=str(path), sha256=_module('cad_verify_v4_ledger').file_sha(path),
                bytes=path.stat().st_size)


def authorized_native_inputs(job, paths, input_manifest):
    """Admit bound data checking, never a model allowance or a CLI bypass."""
    record = job.get('execution_manifest')
    if record is None:
        if input_manifest.get('evidence_mode') != 'independent_dev':
            raise ValueError('neutral_checker_independent_dev_only')
        return None
    if (not isinstance(record, dict) or set(record) != {'path', 'sha256', 'bytes'}
            or not Path(record['path']).is_absolute()):
        raise ValueError('neutral_checker_execution_manifest_record')
    path = _file(record, ROOT)
    ledger, trials = _module('cad_verify_v4_ledger'), _module('cad_verify_v4_trials')
    header = ledger.read_json(path)
    if header.get('evidence_mode') == 'unit_mock':
        frozen, _ = trials.verify_trial(path, verifier=ledger.read_json, allow_mock=True)
    else:
        frozen, _ = trials.verify_trial(path)
    claim = trials.verify_execution_claim(path, frozen)
    registration = frozen['registration_data']
    actual = {key: dict(sha256=ledger.file_sha(paths[key]), bytes=paths[key].stat().st_size)
              for key in ('manifest', 'prepared', 'card', 'context')}
    names = dict(manifest='input_manifest', prepared='prepared', card='card', context='context')
    matching = []
    for entry in registration.get('entries', []) + registration.get('pairs', []):
        if entry.get('profile') != job.get('profile', 'c-s1') or not all(field in entry for field in names.values()):
            continue
        if all(entry[field] in frozen['source_files']
               and all(actual[key][part] == frozen['source_files'][entry[field]][part]
                       for part in ('sha256', 'bytes')) for key, field in names.items()):
            matching.append(entry['id'])
    if not matching:
        raise ValueError('neutral_checker_registered_input_tuple_required')
    if input_manifest.get('evidence_mode') not in ('independent_dev', 'custodian'):
        raise ValueError('neutral_checker_input_evidence_mode')
    _file(record, ROOT)
    return dict(execution_manifest=record, claim_file=claim['claim_file'], registered_entries=matching,
                frozen_evidence_mode=frozen['evidence_mode'], model_authorization=False)


def verify_native(App, job, out):
    """Score two submitted representations with a frozen checker-only context."""
    import Part
    s1, ledger, inputs, compiler, metrics = (_module(n) for n in (
        'cad_verify_v4_s1', 'cad_verify_v4_ledger', 'cad_verify_v4_inputs',
        'cad_verify_v4_compile', 'cad_verify_v4_artifact_judges'))
    profile = job.get('profile', 'c-s1')
    paths = {key: s1.safe_path(job[key], regular=True) for key in ('manifest', 'prepared', 'card', 'context', 'bundle')}
    admission = authorized_native_inputs(job, paths, ledger.read_json(paths['manifest']))
    manifest = inputs.load_manifest(paths['manifest'])
    if admission is None and manifest['evidence_mode'] != 'independent_dev':
        raise ValueError('neutral_checker_independent_dev_only')
    context = metrics.validate_context(ledger.read_json(paths['context']), paths['manifest'],
                                      paths['prepared'], paths['card'], profile=profile)
    prepared, card = ledger.read_json(paths['prepared']), ledger.read_json(paths['card'])
    expected_solids = metrics.expected_solid_count(context, prepared)
    bundle, files, extensions = load_bundle(paths['bundle'], profile=profile)
    execution = _module('cad_verify_v4_runtime')
    runtime_path = s1.safe_path(job['runtime_binding'], regular=True)
    runtime_record = dict(path=str(runtime_path), sha256=ledger.file_sha(runtime_path), bytes=runtime_path.stat().st_size)
    snapshot = ledger.read_json(runtime_path)
    execution.verify(snapshot, root=ROOT, extension_paths=extensions.values())
    before = {key + '_sha256': ledger.file_sha(path) for key, path in paths.items()}
    code_bindings = s1.implementation_bindings(ROOT, profile=profile)
    assets = {inputs.resolve_asset(paths['manifest'], asset_id)['path'] for asset_id in manifest['assets']}
    _guard_archive(files['native'], extensions, assets)
    _import_extensions(extensions)
    doc = App.openDocument(str(files['native']))
    if doc is None:
        raise ValueError('native_document_open_failed')
    body = _body(doc, bundle['output_object'], expected_solids=expected_solids)
    for obj in doc.Objects:
        if obj.TypeId.endswith('Python') and 'Proxy' in obj.PropertiesList:
            proxy = obj.Proxy
            if proxy is None or type(proxy).__module__ not in extensions:
                raise ValueError('native_python_feature_not_restored')
        obj.touch()
    with compiler.validated_contour_sources(doc):
        doc.recompute()
        check_document(doc, body, expected_solids=expected_solids)
        editability, editable = operative(App, doc, body, bundle['probes'], expected_solids=expected_solids)
        restored = compiler.shape_measurements(body.Shape, tight_bounds=profile in ('c-s2', 'c-s3'),
                                               expected_solids=expected_solids)
    step_doc = App.newDocument('NeutralSTEP')
    if expected_solids > 1:
        # STEP readers may expose one object per transferred solid. Read the
        # complete file topology as one compound, without fusing or dropping it.
        step_shape = Part.Shape()
        step_shape.read(str(files['step']))
        feature = step_doc.addObject('Part::Feature', 'ImportedCompound')
        feature.Shape = step_shape
        step_doc.recompute()
    else:
        Part.insert(str(files['step']), step_doc.Name)
        step_doc.recompute()
        shapes = [obj.Shape for obj in step_doc.Objects if hasattr(obj, 'Shape') and not obj.Shape.isNull()]
        if len(shapes) != 1:
            raise ValueError('step_single_output_object_required')
        step_shape = shapes[0]
    imported = compiler.shape_measurements(step_shape, tight_bounds=profile in ('c-s2', 'c-s3'),
                                           expected_solids=expected_solids)
    bound_delta = max(abs(a-b) for a,b in zip(restored['bounds_mm'], imported['bounds_mm']))
    volume_delta = abs(restored['volume_mm3'] - imported['volume_mm3'])
    evidence = {'fcstd_reopened': True, 'step_reopened': True, 'editable': editable,
                'bounds_difference_mm': bound_delta, 'volume_difference_mm3': volume_delta}
    fcstd_judge = metrics.judge(context, paths['manifest'], prepared, body, card, native_evidence=evidence)
    step_judge = metrics.judge(context, paths['manifest'], prepared, step_shape, card, native_evidence=evidence)
    roundtrip = _module('cad_verify_v4_worker')._roundtrip_criteria(card, evidence)
    if before != {key + '_sha256': ledger.file_sha(path) for key, path in paths.items()}:
        raise ValueError('neutral_checker_input_changed')
    if code_bindings != s1.implementation_bindings(ROOT, profile=profile):
        raise ValueError('neutral_checker_implementation_changed')
    load_bundle(paths['bundle'], profile=profile)
    execution.verify(snapshot, root=ROOT, extension_paths=extensions.values())
    if ledger.file_sha(runtime_path) != runtime_record['sha256']:
        raise ValueError('neutral_execution_runtime_file_changed')
    if admission is not None:
        _file(admission['execution_manifest'], ROOT)
        _file(admission['claim_file'], ROOT)
    statuses = [fcstd_judge['status'], step_judge['status']] + [row['status'] for row in roundtrip]
    status = 'FAIL' if 'FAIL' in statuses else 'PASS' if all(value == 'PASS' for value in statuses) else 'UNVERIFIED'
    return dict(schema='cad-harness.artifact-check-result.v4', profile=profile, family=context['family'],
                status=status, geometry_ok=True, editability_ok=editable, bindings=before,
                artifacts={key: dict(path=str(files[key]), sha256=bundle[key]['sha256'], bytes=bundle[key]['bytes'])
                           for key in ('native', 'step')},
                source_paths={key: str(value) for key,value in paths.items()}, code_bindings=code_bindings,
                measurements={'fcstd': restored, 'step': imported}, native_evidence=evidence,
                editability=editability, roundtrip=roundtrip,
                judges={'fcstd': fcstd_judge, 'step': step_judge}, runtime_binding=runtime_record,
                execution_admission=admission, live_calls=0)


def check(manifest_path, prepared_path, card_path, context_path, bundle_path, run_dir, *,
          profile='c-s1', timeout=300, process=None, execution=None):
    """Closed-stdin native artifact check with full durable streams and ledger."""
    s1, ledger, metrics = (_module(n) for n in ('cad_verify_v4_s1', 'cad_verify_v4_ledger', 'cad_verify_v4_artifact_judges'))
    manifest_path, _, _ = s1._manifest_inputs(manifest_path, prepared_path, profile=profile, execution=execution)
    prepared_path, card_path, context_path, bundle_path = (s1.safe_path(p, regular=True)
        for p in (prepared_path, card_path, context_path, bundle_path))
    metrics.validate_context(ledger.read_json(context_path), manifest_path, prepared_path, card_path, profile=profile)
    load_bundle(bundle_path, profile=profile)
    authority = {} if execution is None else {'execution_manifest': execution_manifest_record(execution)}
    out = ledger.new_directory(s1.safe_path(run_dir))
    mode = execution.mode if execution is not None else 'independent_dev'
    with ledger.Journal(out / 'ledger.jsonl', out.name,
                        'authorized-neutral-artifact' if execution is not None else 'neutral-artifact-development') as journal:
        tick = time.monotonic()
        journal.append('run_started', profile=profile, evidence_mode=mode, live_calls=0)
        try:
            result = s1.native_work('artifact-verify', out / 'native', journal, timeout=timeout,
                process=process, profile=profile, manifest=str(manifest_path), prepared=str(prepared_path),
                card=str(card_path), context=str(context_path), bundle=str(bundle_path), **authority)
        except BaseException as exc:
            journal.append('run_finished', wall_s=time.monotonic()-tick, active_s=time.monotonic()-tick,
                           stop_reason=str(exc), live_calls=0)
            raise
        journal.append('run_finished', wall_s=time.monotonic()-tick, active_s=time.monotonic()-tick,
                       stop_reason=None, live_calls=0)
    summary = dict(schema='cad-harness.artifact-check.v4', profile=profile,
                   evidence_mode=mode, status=result['status'],
                   result_path=str(out / 'native/result.json'), result=result,
                   live_calls=0, live_cad_runs=0, native_work=1, holdout='not_run', pilot='not_run',
                   authorization=None, final_v4_ready=False)
    if execution is not None:
        session = getattr(execution, 'session', execution)
        summary.update(summary_path=str(out / 'summary.json'), ledger_path=str(out / 'ledger.jsonl'),
                       execution_manifest_sha256=ledger.file_sha(session.manifest_path))
    ledger.write_json(out / 'summary.json', summary)
    return summary
